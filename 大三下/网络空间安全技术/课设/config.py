# ---------------------------------------------------------------------------
# 个性化安全阈值  ——  设计者：程泽凯（学号尾号 1）
# ---------------------------------------------------------------------------

# 【规则一：登录失败限制 / 暴力尝试】
# 设计理由：参考任务书“5 分钟内失败超过 5 次”，结合本人实验，
#           将窗口设为 5 分钟、阈值设为 5 次。达到后锁定账号 10 分钟。
BRUTE_FORCE_WINDOW_MINUTES = 5      # 暴力尝试统计窗口（分钟）
MAX_FAILED_ATTEMPTS = 5             # 窗口内允许的最大失败次数
ACCOUNT_LOCK_MINUTES = 10           # 触发后账号临时锁定时长（分钟）

# 【规则二：异地登录模拟】
# 设计理由：正常用户短时间内不会在多个 IP 间切换。
#           设定 10 分钟内同一账号出现 ≥ 2 个不同 IP 即判异地。
MULTI_IP_WINDOW_MINUTES = 10        # 异地检测窗口（分钟）
MULTI_IP_THRESHOLD = 2              # 窗口内不同 IP 数达到此值即告警

# 【规则三：非工作时间登录】
# 设计理由：本人作息为白天上机，夜间 23:00 至次日 06:00 视为异常时段。
OFF_HOURS_START = 23                # 非工作时间起点（含），24 小时制
OFF_HOURS_END = 6                   # 非工作时间终点（不含）

# 【规则四：高频登录】
# 设计理由：人工登录 1 分钟内不可能超过 10 次，超过即疑似脚本刷登录。
HIGH_FREQ_WINDOW_SECONDS = 60       # 高频统计窗口（秒）
HIGH_FREQ_THRESHOLD = 10            # 窗口内请求次数达到此值即告警

